const clean = (raw) => raw
  .replace(/&amp;/g, "&").replace(/&#0?39;|&apos;|&rsquo;/g, "’").replace(/&quot;/g, '"')
  .replace(/&nbsp;/g, " ").replace(/&#(\d+);/g, (_, d) => String.fromCharCode(Number(d)))
  .replace(/\s+/g, " ")
  // Publishers suffix their own name after a dash or pipe; the section already shows the source.
  .replace(/\s*[|–—-]\s*(Business ?Wire|PR ?Newswire|MassDevice|Fierce ?Biotech|MedTech ?Dive|Endovascular Today|Vascular News|DAIC|Novo Holdings)[^|]*$/i, "")
  .trim();

const results = [];
for (const [company, url] of links) {
  try {
    const response = await fetch(url, { headers: { "user-agent": UA }, redirect: "follow", signal: AbortSignal.timeout(25000) });
    if (!response.ok) throw new Error(String(response.status));
    const html = await response.text();
    const title = clean(html.match(/<title[^>]*>([\s\S]*?)<\/title>/i)?.[1] ?? "");
    if (!title || title.length < 15) throw new Error("no usable <title>");
    results.push({ company, url, title, source: new URL(url).hostname.replace(/^www\./, "") });
    console.log(`OK   ${company.padEnd(22)} ${title.slice(0, 90)}`);
  } catch (error) {
    console.log(`MISS ${company.padEnd(22)} ${url} (${error.message})`);
  }
}

await mkdir("src/data", { recursive: true });
await writeFile("src/data/portfolio-news.ts", `// Generated by scripts/fetch-portfolio-news.mjs from the news links in AMED's website brief.
// Headlines are the publishers' own <title> text — do not hand-edit; re-run the script instead.

export type PortfolioNews = { company: string; title: string; source: string; url: string };

export const portfolioNews: PortfolioNews[] = ${JSON.stringify(results, null, 2)};
`);
